function completeTranslations(data) {
  const productKeys = new Set([
    data.name,
    data.series,
    data.category,
    data.intro,
    ...data.stats.flatMap(({ label, value, unit }) => [label, value, unit]),
    ...data.sellingPoints.flatMap(({ title, description }) => [title, description]),
    data.quote.label,
    data.quote.description,
    data.inquiry.primaryLabel,
    data.inquiry.secondaryLabel,
    data.overview.title,
    data.overview.body,
    ...data.overview.miniSpecs.flatMap(({ title, description }) => [title, description]),
    ...data.highlights.flatMap(({ title, description }) => [title, description]),
    data.technical.title,
    data.technical.subtitle,
    ...data.technical.groups.flatMap((group) => [
      group.title,
      ...group.items.flatMap(({ label, value }) => [label, value]),
    ]),
  ]);
  const keys = new Set([
    ...commonTranslationKeys,
    ...Object.keys(data.translations.en),
    ...productKeys,
  ]);
  keys.delete("");

  const productEnglishSources = new Map(
    [...productKeys]
      .filter(Boolean)
      .map((key) => [
        key,
        commonTranslationData.translations.en[key] ??
          data.translations.en[key] ??
          key,
      ]),
  );

  function translatedValue(language, key, englishSource = key) {
    return (
      commonTranslationData.translations[language][key] ??
      data.translations[language][key] ??
      commonTranslationData.translations[language][englishSource] ??
      data.translations[language][englishSource] ??
      commonTranslationData.translations.en[key] ??
      data.translations.en[key] ??
      englishSource
    );
  }

  return Object.fromEntries(
    requiredLanguages.map((language) => {
      const copy = {};
      for (const key of keys) {
        copy[key] = translatedValue(language, key);
      }
      // Product content is rendered in English before the browser applies the
      // selected language. Keep an alias for that rendered English source even
      // when a model's translation map is keyed by its original Chinese copy.
      for (const [key, englishSource] of productEnglishSources) {
        copy[englishSource] = translatedValue(language, key, englishSource);
      }
      return [language, copy];
    }),
  );
}

function renderPage(data) {
  const payload = JSON.stringify({
    modelId: data.id,
    defaultLanguage: "en",
    translations: completeTranslations(data),
  }).replaceAll("<", "\\u003c");
  const replacements = {
    "{{GENERATED_MARKER}}": generatedMarker,
    "{{PAGE_TITLE}}": escapeHtml(data.page.title),
    "{{PAGE_DESCRIPTION}}": escapeHtml(data.page.description),
    "{{MODEL_ID}}": escapeHtml(data.id),
    "{{MODEL_NAME}}": escapeHtml(data.name),
    "{{HERO_HTML}}": renderHero(data),
    "{{TABS_HTML}}": renderTabs(data),
    "{{OVERVIEW_HTML}}": renderOverview(data),
    "{{HIGHLIGHTS_HTML}}": renderHighlights(data),
    "{{TECHNICAL_HTML}}": renderTechnical(data),
    "{{I18N_JSON}}": payload,
  };
  let output = template;
  for (const [token, value] of Object.entries(replacements)) {
    if (!output.includes(token)) throw new Error(`Template token is missing: ${token}`);
    output = output.replaceAll(token, value);
  }
  if (/\{\{[A-Z0-9_]+\}\}/u.test(output)) throw new Error("Unresolved template token.");
  return `${output.replace(/\r\n/g, "\n").trimEnd()}\n`;
}

function validateHtml(html, data) {
  if (
    /\uFFFD|浜у搧|鏍稿績|鈫\?|鎶€鏈|<\?\/(?:button|b)&gt;/u.test(html)
  ) {
    throw new Error("Generated HTML contains a replacement character or mojibake marker.");
  }
  const voidElements = new Set([
    "area",
    "base",
    "br",
    "col",
    "embed",
    "hr",
    "img",
    "input",
    "link",
    "meta",
    "param",
    "source",
    "track",
    "wbr",
  ]);
  const stack = [];
  for (const match of html.matchAll(/<\/?([a-z][a-z0-9-]*)\b[^>]*>/giu)) {
    const token = match[0];
    const name = match[1].toLowerCase();
    if (voidElements.has(name) || token.endsWith("/>")) continue;
    if (token.startsWith("</")) {
      const opened = stack.pop();
      if (opened !== name) {
        throw new Error(`Malformed HTML: expected </${opened || "none"}>, found </${name}>.`);
      }
    } else {
      stack.push(name);
    }
  }
  if (stack.length) throw new Error(`Malformed HTML: unclosed <${stack.at(-1)}>.`);
  if (!html.includes(`<!-- ${generatedMarker} -->`)) throw new Error("Generated marker missing.");
  if ((html.match(/<a href="#sy300-main-image" class="sy300-preview-still(?: is-active)?"/g) || []).length !== 5) {
    throw new Error("Generated HTML must contain exactly five gallery controls.");
  }
  if ((html.match(/data-product-detail-highlight-open/g) || []).length !== 4) {
    throw new Error("Generated HTML must contain exactly four highlight cards.");
  }
  if (!html.includes(`id="product-detail-i18n"`)) throw new Error("Embedded i18n missing.");
  if (/fetch\s*\(/u.test(html)) throw new Error("Generated HTML may not fetch product JSON.");
  const panelImage = toPanelSiteAssetUrl(data.panelImage || data.banner.image);
  if (!html.includes(`--product-panel-image:url('${escapeHtml(panelImage)}')`)) {
    throw new Error(`Generated panel image path is invalid: ${panelImage}`);
  }
  for (const image of [...data.gallery, ...data.highlights.map((item) => ({
    src: item.image,
    alt: item.alt,
  }))]) {
    if (!html.includes(escapeHtml(image.src)) || !html.includes(escapeHtml(image.alt))) {
      throw new Error(`Generated image or alt missing: ${image.src}`);
    }
  }
  for (const value of [data.name, data.intro, data.overview.body, data.inquiry.href]) {
    if (!html.includes(escapeHtml(value))) throw new Error(`Static content missing: ${value}`);
  }
}

let modelIds;
if (args[0] === "--all") {
  modelIds = (await fs.readdir(dataDirectory))
    .filter((name) => name.endsWith(".json"))
    .map((name) => name.slice(0, -5))
    .sort();
} else {
  modelIds = [...new Set(args)];
}
for (const id of modelIds) {
  if (!/^[a-z0-9-]+$/u.test(id)) throw new Error(`Invalid model id: ${id}`);
}

for (const id of modelIds) {
  const dataPath = path.join(dataDirectory, `${id}.json`);
  const outputPath = path.join(outputDirectory, `${id}.html`);
  const temporaryPath = `${outputPath}.${process.pid}.tmp`;
  try {
    const data = JSON.parse(await fs.readFile(dataPath, "utf8"));
    validateProduct(data, id);
    await validateAssets(data);
    const html = renderPage(data);
    validateHtml(html, data);
    await fs.writeFile(temporaryPath, html, "utf8");
    const reread = await fs.readFile(temporaryPath, "utf8");
    if (reread !== html) throw new Error(`UTF-8 verification failed for ${id}.`);
    await fs.rename(temporaryPath, outputPath);
    console.log(`built frontend/pages/${id}.html`);
  } catch (error) {
    await fs.rm(temporaryPath, { force: true });
    throw error;
  }
}
