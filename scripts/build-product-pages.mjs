import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const frontendDirectory = path.join(root, "frontend");
const templatePath = path.join(root, "frontend", "product-detail", "template.html");
const schemaPath = path.join(root, "frontend", "product-detail", "schema.json");
const commonTranslationsPath = path.join(
  root,
  "shared",
  "product-detail-common-translations.json",
);
const dataDirectory = path.join(root, "frontend", "product-detail", "data");
const outputDirectory = path.join(frontendDirectory, "pages");
const generatedMarker = "generated by scripts/build-product-pages.mjs; do not edit";
const requiredLanguages = ["en", "zh-CN", "zh-TW", "ru", "ar", "es", "pt"];
const requiredAngles = ["front", "left-front", "left-side", "left-rear", "rear"];

function usage() {
  return [
    "Usage:",
    "  node scripts/build-product-pages.mjs <model-id> [<model-id> ...]",
    "  node scripts/build-product-pages.mjs --all",
    "",
    "No output is written unless a model id or --all is supplied.",
  ].join("\n");
}

const args = process.argv.slice(2);
if (!args.length || args.includes("--help") || args.includes("-h")) {
  console[args.length ? "log" : "error"](usage());
  process.exit(args.length ? 0 : 2);
}
if (args.includes("--all") && args.length !== 1) {
  throw new Error("--all cannot be combined with model ids.");
}

const [template, schema, commonTranslationData] = await Promise.all([
  fs.readFile(templatePath, "utf8"),
  fs.readFile(schemaPath, "utf8").then(JSON.parse),
  fs.readFile(commonTranslationsPath, "utf8").then(JSON.parse),
]);

if (
  commonTranslationData.schemaVersion !== 1 ||
  JSON.stringify(commonTranslationData.languages) !==
    JSON.stringify(requiredLanguages)
) {
  throw new Error("Shared product-detail translations must use schemaVersion 1 and the required languages.");
}
const commonSourceKeys = Object.keys(commonTranslationData.translations.en);
if (commonSourceKeys.length !== 32) {
  throw new Error(
    `Shared product-detail translations must contain exactly 32 keys; received ${commonSourceKeys.length}.`,
  );
}
for (const language of requiredLanguages) {
  const copy = commonTranslationData.translations[language];
  if (
    !copy ||
    JSON.stringify(Object.keys(copy).sort()) !==
      JSON.stringify([...commonSourceKeys].sort()) ||
    Object.values(copy).some((value) => typeof value !== "string" || !value)
  ) {
    throw new Error(`Shared product-detail translations are invalid for ${language}.`);
  }
}
const commonTranslationKeys = new Set(commonSourceKeys);

function resolveRef(ref) {
  if (!ref.startsWith("#/")) throw new Error(`Unsupported schema reference: ${ref}`);
  return ref
    .slice(2)
    .split("/")
    .reduce((value, key) => value[key.replaceAll("~1", "/").replaceAll("~0", "~")], schema);
}

function validateSchema(value, rule, location = "$") {
  if (rule.$ref) return validateSchema(value, resolveRef(rule.$ref), location);
  if (rule.enum && !rule.enum.includes(value)) {
    throw new Error(`${location} must be one of: ${rule.enum.join(", ")}`);
  }
  if (rule.type === "object") {
    if (!value || typeof value !== "object" || Array.isArray(value)) {
      throw new Error(`${location} must be an object.`);
    }
    for (const key of rule.required || []) {
      if (!Object.prototype.hasOwnProperty.call(value, key)) {
        throw new Error(`${location}.${key} is required.`);
      }
    }
    if (rule.minProperties && Object.keys(value).length < rule.minProperties) {
      throw new Error(`${location} must contain at least ${rule.minProperties} properties.`);
    }
    if (rule.additionalProperties === false) {
      for (const key of Object.keys(value)) {
        if (!Object.prototype.hasOwnProperty.call(rule.properties || {}, key)) {
          throw new Error(`${location}.${key} is not allowed.`);
        }
      }
    }
    for (const [key, item] of Object.entries(value)) {
      const childRule = rule.properties?.[key] || rule.additionalProperties;
      if (childRule && typeof childRule === "object") {
        validateSchema(item, childRule, `${location}.${key}`);
      }
    }
  } else if (rule.type === "array") {
    if (!Array.isArray(value)) throw new Error(`${location} must be an array.`);
    if (rule.minItems !== undefined && value.length < rule.minItems) {
      throw new Error(`${location} must contain at least ${rule.minItems} items.`);
    }
    if (rule.maxItems !== undefined && value.length > rule.maxItems) {
      throw new Error(`${location} must contain at most ${rule.maxItems} items.`);
    }
    value.forEach((item, index) => validateSchema(item, rule.items, `${location}[${index}]`));
  } else if (rule.type === "string") {
    if (typeof value !== "string") throw new Error(`${location} must be a string.`);
    if (rule.minLength !== undefined && value.length < rule.minLength) {
      throw new Error(`${location} must not be empty.`);
    }
    if (rule.pattern && !new RegExp(rule.pattern, "u").test(value)) {
      throw new Error(`${location} does not match ${rule.pattern}.`);
    }
  } else if (rule.type === "integer") {
    if (!Number.isInteger(value)) throw new Error(`${location} must be an integer.`);
  }
}

function validateProduct(data, expectedId) {
  validateSchema(data, schema);
  const validateTextIntegrity = (value, location = "$") => {
    if (typeof value === "string") {
      if (/\uFFFD/u.test(value) || (value.includes("?") && !/^inquiry\.html\?/u.test(value))) {
        throw new Error(`${location} contains a replacement or mojibake marker.`);
      }
      return;
    }
    if (Array.isArray(value)) {
      value.forEach((item, index) => validateTextIntegrity(item, `${location}[${index}]`));
      return;
    }
    if (value && typeof value === "object") {
      for (const [key, item] of Object.entries(value)) {
        validateTextIntegrity(key, `${location}.<key>`);
        validateTextIntegrity(item, `${location}.${key}`);
      }
    }
  };
  validateTextIntegrity(data);
  if (data.id !== expectedId) {
    throw new Error(`Data id "${data.id}" does not match requested model "${expectedId}".`);
  }
  if (JSON.stringify(data.languages) !== JSON.stringify(requiredLanguages)) {
    throw new Error(`$.languages must be exactly ${requiredLanguages.join(", ")}.`);
  }
  if (JSON.stringify(data.gallery.map((image) => image.angle)) !== JSON.stringify(requiredAngles)) {
    throw new Error(`$.gallery angles must be exactly ${requiredAngles.join(", ")}.`);
  }
  const sourceKeys = Object.keys(data.translations.en).sort();
  for (const language of requiredLanguages) {
    const keys = Object.keys(data.translations[language]).sort();
    if (JSON.stringify(keys) !== JSON.stringify(sourceKeys)) {
      throw new Error(`$.translations.${language} must contain exactly the English source keys.`);
    }
    const overriddenCommonKey = keys.find((key) =>
      commonTranslationKeys.has(key),
    );
    if (overriddenCommonKey) {
      throw new Error(
        `$.translations.${language} may not override shared key: ${overriddenCommonKey}`,
      );
    }
  }
  const images = [
    ...data.gallery.map(({ src, alt }) => ({ src, alt })),
    ...data.highlights.map(({ image: src, alt }) => ({ src, alt })),
    { src: data.banner.image, alt: data.banner.alt },
  ];
  images.forEach(({ src, alt }, index) => {
    if (!src || !alt) throw new Error(`Image ${index + 1} requires src and alt.`);
    if (/white|transparent|light[-_ ]?(?:gray|grey)/iu.test(path.basename(src))) {
      throw new Error(`Final product image may not use a white/light/transparent asset: ${src}`);
    }
  });
}

function toPanelSiteAssetUrl(source) {
  const [, cleanSource, suffix] = String(source).match(/^([^?#]*)(.*)$/u);
  const absoluteAsset = path.resolve(outputDirectory, cleanSource);
  const frontendRelativePath = path
    .relative(frontendDirectory, absoluteAsset)
    .split(path.sep)
    .join("/");
  if (frontendRelativePath.startsWith("../") || path.isAbsolute(frontendRelativePath)) {
    throw new Error(`Product asset is outside frontend: ${source}`);
  }
  const cssRelativePath = path
    .relative(path.join(frontendDirectory, "assets", "css"), absoluteAsset)
    .split(path.sep)
    .join("/");
  if (path.isAbsolute(cssRelativePath)) {
    throw new Error(`Panel asset cannot resolve from product-detail.css: ${source}`);
  }
  return `${cssRelativePath}${suffix}`;
}

async function validateAssets(data) {
  const sources = new Set([
    ...(data.panelImage ? [data.panelImage] : []),
    ...data.gallery.map((image) => image.src),
    ...data.highlights.map((item) => item.image),
    data.banner.image,
  ]);
  for (const source of sources) {
    const cleanSource = source.split(/[?#]/u, 1)[0];
    if (!cleanSource.startsWith("../assets/")) {
      throw new Error(`Product asset must resolve from frontend/pages: ${source}`);
    }
    try {
      await fs.access(path.resolve(outputDirectory, cleanSource));
    } catch {
      throw new Error(`Product asset does not exist: ${source}`);
    }
  }
  const panelSource = data.panelImage || data.banner.image;
  const panelSourcePath = panelSource.split(/[?#]/u, 1)[0];
  const panelSitePath = toPanelSiteAssetUrl(panelSource).split(/[?#]/u, 1)[0];
  const pageResolvedPanel = path.resolve(outputDirectory, panelSourcePath);
  const expectedPanelSitePath = path
    .relative(path.join(frontendDirectory, "assets", "css"), pageResolvedPanel)
    .split(path.sep)
    .join("/");
  if (panelSitePath !== expectedPanelSitePath) {
    throw new Error(
      `Panel image CSS URL resolves to ${panelSitePath}, expected ${expectedPanelSitePath}.`,
    );
  }
}

